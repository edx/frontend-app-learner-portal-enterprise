/**
 * Regenerates `index.ts` (the goldens as string exports, since webpack has no `.sse` rule)
 * and the hash table in `README.md` from the `.sse` files in this folder.
 *
 * Run after copying new goldens from enterprise-access:
 *   node src/components/dashboard/main-content/personalized-search/stream/__fixtures__/syncFixtures.js <source>
 * where <source> describes where the copies came from (e.g. "enterprise-access@<sha>").
 */
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const FIXTURE_FILES = [
  'normal_turn.sse',
  'off_topic_turn.sse',
  'no_match_turn.sse',
  'degraded_turn.sse',
  'error_turn.sse',
];

const exportName = (file) => file.replace('.sse', '').replace(/_([a-z])/g, (_, c) => c.toUpperCase());

const source = process.argv[2];
if (!source) {
  console.error('usage: node syncFixtures.js <source description>');
  process.exit(1);
}

const dir = __dirname;
const contents = FIXTURE_FILES.map((file) => [file, fs.readFileSync(path.join(dir, file), 'utf8')]);

const index = [
  '/* eslint-disable */',
  '// Generated by syncFixtures.js from the .sse files in this folder. Do not edit by hand.',
  ...contents.map(([file, body]) => `export const ${exportName(file)} = ${JSON.stringify(body)};`),
  '',
  'export const goldenFixtures = {',
  ...FIXTURE_FILES.map((file) => `  '${file}': ${exportName(file)},`),
  '};',
  '',
].join('\n');
fs.writeFileSync(path.join(dir, 'index.ts'), index);

const readmePath = path.join(dir, 'README.md');
const readme = fs.readFileSync(readmePath, 'utf8');
const table = [
  '<!-- hashes:start -->',
  `Source: ${source}`,
  '',
  '| File | sha256 |',
  '| --- | --- |',
  ...contents.map(([file, body]) => `| \`${file}\` | \`${crypto.createHash('sha256').update(body).digest('hex')}\` |`),
  '<!-- hashes:end -->',
].join('\n');
fs.writeFileSync(readmePath, readme.replace(/<!-- hashes:start -->[\s\S]*<!-- hashes:end -->/, table));
console.log('Updated index.ts and README.md hashes');
